function parseHeadingLines(lines) {
  const headings = [];
  let fenceMarker = null;
  let inFrontmatter = false;
  let previousLineIsParagraph = false;
  let paragraphStart = null;
  for (let index = 0; index < lines.length; index++) {
    const line = index === 0 ? lines[index].replace(/^\uFEFF/, "") : lines[index];
    if (index === 0 && /^---[ \t]*$/.test(line)) {
      inFrontmatter = true;
      previousLineIsParagraph = false;
      paragraphStart = null;
      continue;
    }
    if (inFrontmatter) {
      if (/^(?:---|\.\.\.)[ \t]*$/.test(line)) {
        inFrontmatter = false;
      }
      continue;
    }
    const fence = /^ {0,3}(```+|~~~+)/.exec(line);
    if (fence) {
      const marker = fence[1][0];
      if (fenceMarker === null) {
        fenceMarker = marker;
      } else if (fenceMarker === marker) {
        fenceMarker = null;
      }
      previousLineIsParagraph = false;
      paragraphStart = null;
      continue;
    }
    if (fenceMarker !== null) {
      continue;
    }
    const atx = /^ {0,3}(#{1,6})(?:[ \t]+|$)/.exec(line);
    if (atx) {
      headings.push({ line: index, level: atx[1].length });
      previousLineIsParagraph = false;
      paragraphStart = null;
      continue;
    }
    const setext = /^ {0,3}(=+|-+)[ \t]*$/.exec(line);
    if (setext && previousLineIsParagraph) {
      headings.push({
        line: paragraphStart != null ? paragraphStart : index,
        level: setext[1][0] === "=" ? 1 : 2
      });
      previousLineIsParagraph = false;
      paragraphStart = null;
      continue;
    }
    const isParagraph = line.trim().length > 0;
    if (isParagraph && !previousLineIsParagraph) {
      paragraphStart = index;
    } else if (!isParagraph) {
      paragraphStart = null;
    }
    previousLineIsParagraph = isParagraph;
  }
  return headings;
}

